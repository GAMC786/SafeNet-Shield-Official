import { useState } from "react";
import { ExternalLink, Radio, Trash2 } from "lucide-react";
import type { DnsServer } from "@shared/schema";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { CyberCard } from "@/components/CyberCard";
import { usePrivateDns } from "@/hooks/use-private-dns";
import { useTrustTunnelVpn } from "@/hooks/use-trusttunnel-vpn";

type VpnMode = "tunnel" | "system";

export function TrustTunnelVpnCard({ activeDns }: { activeDns?: DnsServer }) {
  const vpn = useTrustTunnelVpn();
  const privateDns = usePrivateDns(activeDns);
  const [mode, setMode] = useState<VpnMode>("tunnel");
  const [deepLink, setDeepLink] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const status = vpn.status;
  const connected = status?.connected === true;
  const stateLabel = !vpn.isAndroid
    ? "Android only"
    : vpn.isLoading
      ? "Checking"
      : connected
        ? "Connected"
        : status?.connecting
          ? "Connecting"
          : status?.configured
            ? "Disconnected"
            : "Server link required";

  const perform = async (action: () => Promise<unknown>) => {
    setBusy(true);
    setError(null);
    try {
      await action();
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "The VPN action failed.");
    } finally {
      setBusy(false);
    }
  };

  return (
    <CyberCard className="flex min-h-[104px] w-full items-center">
      <div className="w-full space-y-4 rounded-lg border border-white/10 bg-background/30 px-3 py-3">
        <div className="flex flex-col gap-3 lg:flex-row lg:items-center lg:justify-between">
          <div className="min-w-0">
            <div className="flex items-center gap-2">
              <Radio className="h-4 w-4 text-primary" />
              <h3 className="text-sm font-medium text-foreground">SafeNet VPN · TrustTunnel</h3>
            </div>
            <p className="mt-1 text-xs text-muted-foreground">
              Route Android traffic through your Linux VPN endpoint. DNS uses AdGuard Family filtering.
            </p>
          </div>
          <Badge variant="outline" className="w-fit text-[10px] font-bold uppercase tracking-wider">
            {stateLabel}
          </Badge>
        </div>

        <div className="flex flex-wrap gap-2 border-t border-white/10 pt-3">
          <Button
            size="sm"
            variant={mode === "tunnel" ? "default" : "outline"}
            onClick={() => setMode("tunnel")}
            aria-pressed={mode === "tunnel"}
            data-testid="button-trusttunnel-mode"
          >
            VPN tunnel
          </Button>
          <Button
            size="sm"
            variant={mode === "system" ? "default" : "outline"}
            onClick={() => setMode("system")}
            aria-pressed={mode === "system"}
            data-testid="button-system-dns-mode"
          >
            System / Private DNS
          </Button>
        </div>

        {mode === "tunnel" ? (
          <div className="space-y-3">
            <p className="text-xs text-muted-foreground">
              Import the <code>tt://</code> client link generated by your Linux endpoint. If its link has no DNS upstream, SafeNet uses{" "}
              <code>tls://family.adguard-dns.com</code>. DNS-based filtering blocks many in-app ads; ads served from first-party domains or encrypted app-specific DNS may remain.
            </p>
            <label className="block space-y-1 text-xs font-medium text-foreground">
              TrustTunnel server link
              <textarea
                value={deepLink}
                onChange={(event) => setDeepLink(event.target.value)}
                placeholder="tt://?..."
                rows={3}
                autoCapitalize="none"
                autoComplete="off"
                spellCheck={false}
                maxLength={12000}
                disabled={!vpn.isAndroid || busy || connected}
                className="w-full resize-y rounded-md border border-white/15 bg-background px-3 py-2 font-mono text-xs text-foreground outline-none focus-visible:ring-2 focus-visible:ring-primary disabled:opacity-50"
                data-testid="input-trusttunnel-link"
              />
            </label>
            <div className="flex flex-wrap items-center gap-2">
              <Button
                size="sm"
                variant="outline"
                onClick={() => void perform(async () => {
                  const result = await vpn.importConfig(deepLink.trim());
                  if (result.configured) setDeepLink("");
                })}
                disabled={!vpn.isAndroid || busy || connected || !deepLink.trim().startsWith("tt://")}
                data-testid="button-import-trusttunnel-link"
              >
                Save server link
              </Button>
              <Button
                size="sm"
                onClick={() => void perform(vpn.connect)}
                disabled={!vpn.isAndroid || busy || connected || !status?.configured}
                data-testid="button-connect-trusttunnel"
              >
                Connect
              </Button>
              {connected && (
                <Button size="sm" variant="outline" onClick={() => void perform(vpn.disconnect)} disabled={busy}>
                  Disconnect
                </Button>
              )}
              {status?.configured && !connected && (
                <Button
                  size="sm"
                  variant="ghost"
                  className="text-muted-foreground"
                  onClick={() => void perform(vpn.removeConfig)}
                  disabled={busy}
                  aria-label="Remove saved TrustTunnel server link"
                >
                  <Trash2 className="mr-1.5 h-3.5 w-3.5" />
                  Remove link
                </Button>
              )}
            </div>
          </div>
        ) : (
          <div className="space-y-3">
            <p className="text-xs text-muted-foreground">
              Use Android’s system DNS without a VPN tunnel. In Private DNS settings, select the provider hostname below. This mode filters DNS requests but does not route other traffic through your Linux endpoint.
            </p>
            <div className="flex flex-wrap items-center gap-2">
              <code className="rounded border border-white/10 bg-background/50 px-2 py-1 text-xs">
                family.adguard-dns.com
              </code>
              <Button
                size="sm"
                variant="outline"
                onClick={() => void perform(async () => {
                  if (connected) await vpn.disconnect();
                  await privateDns.openSettings();
                })}
                disabled={!privateDns.supported || privateDns.isBusy || busy}
                data-testid="button-open-private-dns"
              >
                Open Private DNS settings
                <ExternalLink className="ml-1.5 h-3.5 w-3.5" />
              </Button>
            </div>
          </div>
        )}

        {(error || (vpn.error instanceof Error ? vpn.error.message : null)) && (
          <p className="text-xs text-red-300" role="alert" data-testid="trusttunnel-action-error">
            {error ?? (vpn.error instanceof Error ? vpn.error.message : "TrustTunnel status is unavailable.")}
          </p>
        )}
      </div>
    </CyberCard>
  );
}
